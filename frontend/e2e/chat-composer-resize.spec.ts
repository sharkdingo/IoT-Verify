import { expect, test } from './support/auth'

test('resizes the bottom composer upward without sending in zh-CN at 320px', async ({ page, sharedReadOnlyAccount: auth }) => {
  const chatRequests: string[] = []
  page.on('request', request => {
    if (request.method() === 'POST' && new URL(request.url()).pathname.startsWith('/api/chat')) chatRequests.push(request.url())
  })
  await page.setViewportSize({ width: 320, height: 500 })
  await page.addInitScript(auth => {
    localStorage.setItem('iot_verify_token', auth.token)
    localStorage.setItem('iot_verify_user', JSON.stringify(auth))
    localStorage.setItem('locale', 'zh-CN')
  }, auth)
  await page.goto('/#/board')
  await page.getByTestId('open-ai-assistant').click()
  const panel = page.getByTestId('chat-panel')
  const input = page.getByTestId('chat-input')
  const handle = page.getByRole('separator', { name: '调整输入框高度' })
  await expect(input).toBeVisible()
  await expect(panel).toHaveCSS('transform', 'none')
  await expect.poll(() => panel.evaluate(element => element.getAnimations()
    .filter(animation => animation.playState === 'running' || animation.pending).length)).toBe(0)
  await input.fill('草稿，含 "引号" · draft, with "quotes"')
  await expect(input).toHaveCSS('resize', 'none')
  const before = (await input.boundingBox())!
  const grip = (await handle.boundingBox())!
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
  await page.mouse.down()
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2 - 40, { steps: 5 })
  await page.mouse.up()
  await expect.poll(async () => (await input.boundingBox())!.height).toBeGreaterThan(before.height + 30)
  expect(Math.abs((await input.boundingBox())!.y + (await input.boundingBox())!.height - before.y - before.height)).toBeLessThan(2)
  await expect(handle).toBeFocused()
  await handle.press('Home')
  await expect.poll(async () => (await input.boundingBox())!.height).toBeCloseTo(before.height, 0)
  await handle.press('ArrowUp')
  await expect.poll(async () => (await input.boundingBox())!.height).toBeGreaterThan(before.height + 10)
  await handle.press('ArrowDown')
  await handle.press('End')
  const maximum = Number(await handle.getAttribute('aria-valuemax'))
  await expect.poll(async () => Math.round((await input.boundingBox())!.height)).toBe(maximum)
  await handle.press('ArrowUp')
  expect(Math.round((await input.boundingBox())!.height)).toBe(maximum)
  await handle.press('Tab')
  await expect(input).toBeFocused()
  await expect(input).toHaveValue('草稿，含 "引号" · draft, with "quotes"')
  for (const control of [handle, input, page.getByTestId('chat-send')]) {
    await expect(control).toBeInViewport()
    expect(await control.evaluate(element => {
      const rect = element.getBoundingClientRect()
      const hit = document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)
      return element === hit || element.contains(hit)
    })).toBe(true)
  }
  expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await page.setViewportSize({ width: 320, height: 450 })
  await expect(handle).toHaveAttribute('aria-valuemax', '126')
  await expect(handle).toHaveAttribute('aria-valuenow', '126')
  await expect.poll(async () => Math.round((await input.boundingBox())!.height)).toBe(126)
  await page.setViewportSize({ width: 320, height: 500 })
  await expect(handle).toHaveAttribute('aria-valuemax', '128')
  await handle.press('End')
  await page.getByTestId('chat-close').click()
  await expect(panel).toBeHidden()
  await page.getByTestId('open-ai-assistant').click()
  await expect(input).toHaveValue('草稿，含 "引号" · draft, with "quotes"')
  await expect(panel).toHaveCSS('transform', 'none')
  await expect.poll(() => panel.evaluate(element => element.getAnimations()
    .filter(animation => animation.playState === 'running' || animation.pending).length)).toBe(0)
  await expect.poll(async () => Math.round((await input.boundingBox())!.height)).toBe(maximum)
  expect(chatRequests, 'resizing a draft must not submit an AI request').toEqual([])
})
