import { expandCreation } from './support/controlCenter'
import type { Page } from '@playwright/test'
import { apiBaseURL, createAuthenticatedUser, expect, test } from './support/auth'

const noHints = async (page: Page) => {
  await page.mouse.move(4, 4)
  await expect(page.locator('.iot-hint-tooltip-popper:visible')).toHaveCount(0)
}

for (const locale of ['zh-CN']) {
  for (const width of [320]) {
    test(`editor and result focus transitions in ${locale} at ${width}px`, async ({ page, request }, testInfo) => {
      test.setTimeout(90_000)
      page.setDefaultTimeout(5_000)
      const auth = await createAuthenticatedUser(request)
      const headers = { Authorization: `Bearer ${auth.token}` }
      const post = async (domain: string, data: unknown) => {
        const response = await request.post(`${apiBaseURL}/api/board/${domain}`, { headers, data })
        expect(response.ok(), await response.text()).toBe(true)
      }
      await post('nodes', { devices: [{ id: 'focus_light', templateName: 'Light', label: '焦点测试灯 / Focus test light',
        position: { x: 80, y: 150 }, width: 176, height: 128, state: 'off', variables: [], privacies: [] }], environmentVariablePatches: [] })
      await post('rules', { conditions: [{ deviceName: 'focus_light', targetType: 'mode', attribute: 'SwitchState', relation: '=', value: 'off' }],
        command: { deviceName: 'focus_light', action: 'on' }, ruleString: 'Turn on the test light' })
      await post('specs', { name: 'Safety requirement', id: 'never_on', templateId: '3', templateLabel: 'Never', aConditions: [{ id: 'never_on_a', side: 'a',
        deviceId: 'focus_light', targetType: 'mode', key: 'SwitchState', relation: '=', value: 'on' }], ifConditions: [], thenConditions: [] })
      await page.setViewportSize({ width, height: width === 320 ? 500 : 1080 })
      await page.addInitScript(({ auth, locale }) => {
        localStorage.setItem('iot_verify_token', auth.token)
        localStorage.setItem('iot_verify_user', JSON.stringify(auth))
        localStorage.setItem('locale', locale)
      }, { auth, locale })
      await page.goto('/#/board')
      await expect(page.getByTestId('scene-import')).toBeEnabled()
      const collapse = locale === 'en' ? /^Collapse (Control Center|System Inspector)$/ : /^收起(控制中心|系统检查器)$/
      const expand = locale === 'en' ? /^Expand (Control Center|System Inspector)$/ : /^展开(控制中心|系统检查器)$/
      const control = page.getByTestId('control-center')
      const inspector = page.getByTestId('system-inspector')
      for (const sidebar of [control, inspector]) {
        const close = sidebar.getByRole('button', { name: collapse, exact: true })
        if (await close.isVisible()) await close.click()
        await sidebar.getByRole('button', { name: expand, exact: true }).click()
        await expect(sidebar.getByRole('tab', { selected: true })).toBeFocused()
        await noHints(page)
        await sidebar.getByRole('button', { name: collapse, exact: true }).click()
      }
      await control.getByRole('button', { name: expand, exact: true }).click()
      await page.getByTestId('control-tab-templates').click()
      await expandCreation(page, 'templates')
      let lastTemplate
      for (const template of ['Air Conditioner', 'Light']) {
        lastTemplate = control.getByRole('button', { name: `${locale === 'en' ? 'View template details' : '查看模板详情'}: ${template}`, exact: true })
        await lastTemplate.click()
        await expect(page.locator('.template-preview')).toBeFocused()
        await noHints(page)
        await page.keyboard.press('Escape')
        await expect(page.locator('.template-preview')).toBeHidden()
        await expect(lastTemplate).toBeFocused()
      }
      if (width === 1920) {
        await control.getByRole('button', { name: `${locale === 'en' ? 'View template details' : '查看模板详情'}: Air Conditioner`, exact: true }).click()
        await expect(page.locator('.template-preview')).toBeFocused()
      }
      await lastTemplate!.click()
      const preview = page.locator('.template-preview')
      await expect(preview).toBeFocused()
      await expect(preview).toBeInViewport()
      await expect.poll(() => preview.evaluate(element => {
        const title = element.querySelector('#template-preview-title')!
        const bounds = title.getBoundingClientRect()
        return title.contains(document.elementFromPoint(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2))
      })).toBe(true)
      await noHints(page)
      await page.screenshot({ path: testInfo.outputPath('template-details-focused.png') })
      await page.keyboard.press('Tab')
      await expect(preview.getByRole('button')).toBeFocused()
      await expect(page.locator('.iot-hint-tooltip-popper:visible')).toBeVisible()
      await page.keyboard.press('Escape')
      await expect(preview).toBeHidden()
      await expect(lastTemplate!).toBeFocused()
      if (width === 1920) await lastTemplate!.click()
      await page.getByTestId('control-tab-devices').click()
      await expect(preview).toBeHidden()
      await expect(page.getByTestId('control-tab-devices')).toBeFocused()
      await page.keyboard.press('ArrowRight')
      await expect(page.getByTestId('control-tab-rules')).toBeFocused()
      await page.keyboard.press('End')
      await expect(page.getByTestId('control-tab-specs')).toBeFocused()
      await expandCreation(page, 'specs')
      await page.getByTestId('spec-name').fill('Safety requirement')
      await page.getByTestId('spec-template-select').selectOption('3')
      const addCondition = page.getByTestId('spec-add-condition-a')
      await addCondition.click()
      const condition = page.getByTestId('spec-condition-dialog')
      await expect(condition.getByRole('dialog')).toBeVisible()
      await noHints(page)
      await page.keyboard.press('Shift+Tab')
      expect(await condition.evaluate(element => element.contains(document.activeElement))).toBe(true)
      await page.keyboard.press('Escape')
      await expect(condition).toBeHidden()
      await expect(addCondition).toBeFocused()
      await control.getByRole('button', { name: collapse, exact: true }).click()
      const device = page.locator('[data-node-id="focus_light"]')
      await device.click()
      const details = page.getByTestId('device-dialog')
      await expect(details).toBeVisible()
      await noHints(page)
      await page.keyboard.press('Shift+Tab')
      expect(await details.evaluate(element => element.contains(document.activeElement))).toBe(true)
      await page.keyboard.press('Escape')
      await expect(details).toBeHidden()
      await expect(device).toBeFocused()
      const openTool = async (kind: string) => {
        const restore = page.getByTestId('restore-action-dock')
        if (await restore.isVisible()) await restore.click()
        await page.getByTestId(`open-${kind}-panel`).click()
      }
      await openTool('verification')
      await page.getByTestId('verification-mode-sync').click()
      await page.getByTestId('run-verification').click()
      const verification = page.getByTestId('verification-result-dialog')
      await expect(verification).toBeVisible()
      await expect(verification.getByRole('dialog')).toBeFocused()
      const fixEntry = verification.getByTestId('verification-trace-fix').first()
      await fixEntry.click()
      const fix = page.getByTestId('fix-result-dialog')
      await expect(fix.getByRole('dialog')).toBeFocused()
      await noHints(page)
      await page.keyboard.press('Shift+Tab')
      expect(await fix.evaluate(element => element.contains(document.activeElement))).toBe(true)
      await page.keyboard.press('Escape')
      await expect(fix).toBeHidden()
      await expect(fixEntry).toBeFocused()
      await fixEntry.click()
      await fix.getByTestId('fix-strategy-remove').click()
      await fix.getByTestId('fix-try-current').click()
      const apply = fix.getByTestId('fix-apply-current')
      await expect(apply).toBeEnabled({ timeout: 30_000 })
      await expect(apply).toBeFocused()
      await noHints(page)
      await apply.click()
      const confirmation = page.locator('.el-message-box.fix-removal-confirm')
      await expect(confirmation).toBeFocused()
      await page.keyboard.press('Enter')
      await expect(confirmation).toBeVisible()
      await page.keyboard.press('Escape')
      await expect(confirmation).toBeHidden()
      await expect(fix).toBeVisible()
      await expect(apply).toBeFocused()
      await page.screenshot({ path: testInfo.outputPath('repair-confirmation-dismissed.png') })
      await page.keyboard.press('Escape')
      await expect(fix).toBeHidden()
      await expect(fixEntry).toBeFocused()
      await page.keyboard.press('Escape')
      await expect(verification).toBeHidden()
      await expect(page.getByTestId('open-verification-panel')).toBeFocused()
      await openTool('fuzzing')
      await page.getByTestId('fuzz-max-iterations').fill('1')
      await page.getByTestId('fuzz-path-length').fill('2')
      const advanced = page.getByTestId('fuzzing-panel').locator('details').filter({ has: page.getByTestId('fuzz-population-size') })
      await advanced.locator('summary').click()
      await page.getByTestId('fuzz-population-size').fill('1')
      await page.getByTestId('run-fuzzing').click()
      const result = page.getByTestId('fuzzing-result-dialog')
      await expect(result.getByRole('dialog')).toBeFocused({ timeout: 15_000 })
      await noHints(page)
      await page.screenshot({ path: testInfo.outputPath('exploration-result-focused.png') })
      await page.keyboard.press('Tab')
      await expect(result.getByTestId('close-fuzzing-result')).toBeFocused()
      await expect(page.locator('.iot-hint-tooltip-popper:visible')).toBeVisible()
      await result.getByTestId('reuse-fuzzing-settings').click()
      await expect(result).toBeHidden()
      await expect(page.getByTestId('fuzzing-panel')).toBeFocused()
      await noHints(page)
      await page.keyboard.press('Escape')
      await expect(page.getByTestId('open-fuzzing-panel')).toBeFocused()
      await openTool('simulation')
      await page.getByTestId('simulation-mode-sync').click()
      // Exercise the error surface without substituting any result or task state.
      await page.route('**/api/simulate/traces', route => route.fulfill({ status: 503,
        json: { code: 503, message: 'Simulation transport unavailable' } }))
      await page.getByTestId('run-simulation').click()
      const failure = page.getByTestId('simulation-result-dialog')
      await expect(failure).toBeVisible()
      await noHints(page)
      await page.keyboard.press('Escape')
      await expect(failure).toBeHidden()
      await expect(page.getByTestId('run-simulation')).toBeFocused()
      await page.getByTestId('close-simulation-panel').click()
      const account = page.getByTestId('open-account-center')
      if (await account.isVisible()) await account.click()
      else {
        await page.locator('.scene-actions-menu > summary').click()
        await page.getByTestId('nav-overflow-account').click()
      }
      await page.getByTestId('account-logout').click()
      await expect(page.getByTestId('logout-cancel')).toBeFocused()
      await noHints(page)
      await page.keyboard.press('Escape')
      await expect(page.getByTestId('logout-dialog')).toBeHidden()
      await expect(page.getByTestId('account-logout')).toBeFocused()
      await page.getByTestId('open-account-delete').click()
      await expect(page.getByTestId('account-delete-confirmation')).toBeFocused()
      await noHints(page)
      await page.keyboard.press('Escape')
      await expect(page.getByTestId('account-delete-dialog')).toBeHidden()
      await expect(page.getByTestId('open-account-delete')).toBeFocused()
    })
  }
}
